import { useEffect, useState } from 'react';
import './BoardingAnimation.css';

/*
 * BOARDING ANIMATION — beat sheet
 * --------------------------------
 * Everything below is percentages of a single shared duration, --dur (9s).
 * One CSS variable drives every actor's @keyframes, so nothing can drift
 * out of sync — there are no per-actor delays or durations to keep aligned.
 *
 *   0%  - 12%   Plane enters from off-screen LEFT on a shallow, steady
 *                descent — an approach, not a dive. The attitude never
 *                exceeds ~15deg nose-down.
 *  12%  - 20%   Flare: the nose comes up to level and the wheels meet the
 *                ground line — the SAME line the passengers walk on.
 *  20%  - 30%   Roll-out: level, decelerating to a stop on the park. This is
 *                the only deceleration in the approach, and it is on the ground.
 *  18%  - 39%   Traveller walks on from off-screen LEFT, reaches the door.
 *        40%    Traveller vanishes from the ground; seat 1 (37.15% width)
 *               fades in — a child of the plane, so it now travels with it.
 *  40%  - 44%   Plane waits (nothing moves).
 *  44%  - 61%   Couple walk on from off-screen LEFT, reach the door.
 *        62%    Couple vanish from the ground; seats 2+3 (couple art spans
 *               both, centred 55.4% width) fade in.
 *  62%  - 74%   Plane waits, fully boarded, all three visible.
 *  74%  - 82%   Take-off roll: level, accelerating from the standstill.
 *  82%  - 88%   Rotate: nose lifts from 0deg to the -20deg climb attitude.
 *  88%  - 96%   Climbs out to the RIGHT and leaves the frame entirely.
 *  96%  - 100%  Empty hero while the overlay begins its fade.
 *
 * EVERY waypoint above is generated by scripts/build-boarding-path.mjs and lives
 * in ONE unit, --u, for both axes — so the whole path is geometrically similar
 * at any viewport, the nose angles stay true, and the script refuses to emit a
 * path that runs off screen or under the header at any of fourteen test sizes.
 * There is a separate, reproportioned variant below max-aspect-ratio: 1/1.
 *
 * The aircraft PARKS ON THE GROUND. It used to bottom out at +14u and then
 * climb back to -6u, so it touched down and floated two plane-heights into the
 * air while the passengers walked along a line a full plane-height below the
 * fuselage and vanished into seats they could not have reached. Portrait was
 * always correct; only landscape hovered.
 *
 * After --dur elapses the overlay fades out over --fade-dur (600ms), then
 * the component unmounts itself. Skip jumps straight to unmounted.
 *
 * Tunable geometry lives at the top of BoardingAnimation.css:
 * --u (the single unit everything derives from), --park-x,
 * --person-w (both actors share one scale, see comment there),
 * --seat-clip (how much of the passenger is visible above the seat back),
 * and the seat/ground anchor positions.
 */

const SOURCES = {
  plane: '/intro/plane.svg',
  traveller: '/intro/traveller.png',
  couple: '/intro/couple.png',
};

const DUR_MS = 9000;
const FADE_MS = 600;

/*
 * How long the intro is allowed to wait for its artwork.
 *
 * The overlay cannot start until every image has decoded, or it plays with
 * holes in it. But an intro that begins two seconds late is worse than no intro
 * at all: it drops a full-screen overlay onto a page the visitor has already
 * started reading. Past this budget the sequence is abandoned rather than
 * played late — the same silent skip a missing file already gets.
 *
 * The art is ~176 KB, so this is only ever reached on a genuinely slow link.
 */
const ART_BUDGET_MS = 1200;

function preload(src) {
  return new Promise((resolve, reject) => {
    const img = new Image();
    img.onload = () => {
      if (img.decode) {
        // decode() can reject in some browsers even though the image is
        // usable (e.g. animated/odd formats) — onload already fired, so
        // treat a decode failure as non-fatal.
        img.decode().then(resolve, resolve);
      } else {
        resolve();
      }
    };
    img.onerror = reject;
    img.src = src;
  });
}

export default function BoardingAnimation() {
  const [ready, setReady] = useState(false);
  const [visible, setVisible] = useState(true);
  const [fading, setFading] = useState(false);

  useEffect(() => {
    // Optional-chained like every other reduced-motion check on this page:
    // matchMedia is absent in some embedded webviews and in jsdom, and an
    // unguarded call throws before the animation is even reached.
    if (window.matchMedia?.('(prefers-reduced-motion: reduce)').matches) return;

    let cancelled = false;
    // Fires whether the art arrives late or not at all; both mean "no intro".
    const budget = setTimeout(() => {
      cancelled = true;
    }, ART_BUDGET_MS);

    Promise.all(Object.values(SOURCES).map(preload))
      .then(() => {
        if (!cancelled) setReady(true);
      })
      .catch(() => {
        // one or more images failed to load/decode — skip silently
      })
      .finally(() => clearTimeout(budget));

    return () => {
      cancelled = true;
      clearTimeout(budget);
    };
  }, []);

  useEffect(() => {
    if (!ready) return;
    const fadeTimer = setTimeout(() => setFading(true), DUR_MS);
    const doneTimer = setTimeout(() => setVisible(false), DUR_MS + FADE_MS);
    return () => {
      clearTimeout(fadeTimer);
      clearTimeout(doneTimer);
    };
  }, [ready]);

  if (!ready || !visible) return null;

  return (
    <div
      className={`boarding-overlay${fading ? ' boarding-overlay--fading' : ''}`}
      style={{ '--dur': `${DUR_MS}ms`, '--fade-dur': `${FADE_MS}ms` }}
      aria-hidden="true"
    >
      <button
        type="button"
        className="boarding-skip"
        aria-label="Skip intro animation"
        onClick={() => setVisible(false)}
      >
        Skip
      </button>

      <div className="boarding-plane">
        <img src={SOURCES.plane} alt="" className="boarding-plane__img" draggable="false" />

        {/* Seated passengers are children of the plane element on purpose:
            they inherit its transform for free during takeoff, so there is
            no second animation to keep in sync with the flight path. */}
        <div className="boarding-seat boarding-seat--1">
          <img src={SOURCES.traveller} alt="" className="boarding-seat__img" draggable="false" />
        </div>
        <div className="boarding-seat boarding-seat--23">
          <img src={SOURCES.couple} alt="" className="boarding-seat__img" draggable="false" />
        </div>
      </div>

      <div className="boarding-walker boarding-walker--traveller">
        <img src={SOURCES.traveller} alt="" className="boarding-walker__img" draggable="false" />
      </div>
      <div className="boarding-walker boarding-walker--couple">
        <img src={SOURCES.couple} alt="" className="boarding-walker__img" draggable="false" />
      </div>
    </div>
  );
}
